"""GPX file exporter and route map generator."""

from datetime import datetime, timezone
from pathlib import Path
from typing import Sequence
import folium
from folium.plugins import Fullscreen
import gpxpy
import gpxpy.gpx
import networkx as nx

from hexroute.grid import cell_to_boundary, cell_to_latlng
from hexroute.targets import HexStatus, ScoredHex


def get_path_coordinates(
    graph: nx.MultiDiGraph,
    path_nodes: Sequence[int],
) -> list[tuple[float, float]]:
    """
    Extract high-fidelity (lat, lng) coordinates from a sequence of graph nodes,
    including intermediate geometry vertices along OSM edges.
    """
    if not path_nodes:
        return []

    coords: list[tuple[float, float]] = []

    for i in range(len(path_nodes)):
        node = path_nodes[i]
        n_lat, n_lng = float(graph.nodes[node]["y"]), float(graph.nodes[node]["x"])

        if not coords:
            coords.append((n_lat, n_lng))

        if i < len(path_nodes) - 1:
            next_node = path_nodes[i + 1]
            edge_data = graph.get_edge_data(node, next_node)

            if edge_data and 0 in edge_data and "geometry" in edge_data[0]:
                geom = edge_data[0]["geometry"]
                edge_pts = [(lat, lng) for lng, lat in geom.coords]
                # Avoid duplicate point with previous
                if edge_pts and edge_pts[0] == coords[-1]:
                    edge_pts = edge_pts[1:]
                coords.extend(edge_pts)
            else:
                next_lat = float(graph.nodes[next_node]["y"])
                next_lng = float(graph.nodes[next_node]["x"])
                if coords[-1] != (next_lat, next_lng):
                    coords.append((next_lat, next_lng))

    return coords


def export_route_gpx(
    graph: nx.MultiDiGraph,
    path_nodes: Sequence[int],
    out_path: str | Path = "out/route.gpx",
    route_name: str = "Hexroute Optimized Territory Route",
) -> Path:
    """Export the planned route path as a standard GPX file."""
    out_file = Path(out_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)

    coords = get_path_coordinates(graph, path_nodes)

    gpx = gpxpy.gpx.GPX()
    gpx.name = route_name
    gpx.description = (
        "Generated by Hexroute territory optimiser. "
        "DISCLAIMER: Automated route suggestion. User assumes all risk. "
        "Verify public rights-of-way, private property boundaries, and personal safety before navigating."
    )
    gpx.creator = "Hexroute"

    track = gpxpy.gpx.GPXTrack(
        name=route_name,
        description="Automated route suggestion. Verify all rights-of-way and safety. User assumes all risk.",
    )
    gpx.tracks.append(track)

    segment = gpxpy.gpx.GPXTrackSegment()
    track.segments.append(segment)

    now = datetime.now(timezone.utc)
    for lat, lng in coords:
        segment.points.append(
            gpxpy.gpx.GPXTrackPoint(
                latitude=lat,
                longitude=lng,
                time=now,
            )
        )

    out_file.write_text(gpx.to_xml(), encoding="utf-8")
    return out_file


def generate_route_map(
    graph: nx.MultiDiGraph,
    path_nodes: Sequence[int],
    claimed_hexes: set[str],
    scored_targets: dict[str, ScoredHex],
    total_distance_m: float,
    total_score: float,
    out_path: str | Path = "out/route.html",
    start_lat: float | None = None,
    start_lng: float | None = None,
    newly_claimed_hexes: set[str] | None = None,
    existing_our_hexes: set[str] | None = None,
    team_name: str = "Agile & Fragile",
    team_colour: str = "#8aa4c2",
) -> Path:
    """Generate an interactive Folium map showing the planned route, newly claimed hexes, and team territory."""
    out_file = Path(out_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)

    coords = get_path_coordinates(graph, path_nodes)
    if not coords and start_lat and start_lng:
        coords = [(start_lat, start_lng)]

    center_lat = coords[0][0] if coords else (start_lat or 51.5074)
    center_lng = coords[0][1] if coords else (start_lng or -0.1278)

    m = folium.Map(
        location=[center_lat, center_lng],
        zoom_start=14,
        tiles="OpenStreetMap",
        control_scale=True,
    )
    Fullscreen().add_to(m)

    # Classify claimed hexes if sets are not passed
    new_claims = set(newly_claimed_hexes or ())
    our_territory = set(existing_our_hexes or ())

    if not new_claims and not our_territory:
        for c in claimed_hexes:
            t = scored_targets.get(c)
            if t and t.status == HexStatus.OURS:
                our_territory.add(c)
            elif t and t.final_score > 0.0:
                new_claims.add(c)
            else:
                our_territory.add(c)

    new_group = folium.FeatureGroup(name=f"✨ New Hexes Claimed ({len(new_claims)})", show=True)
    ours_group = folium.FeatureGroup(name=f"🔵 Our Territory ({team_name})", show=True)
    other_targets_group = folium.FeatureGroup(name="🗺️ Surrounding Unclaimed / Enemy Grid", show=False)

    # 1. Render NEWLY CLAIMED hexagons (Score > 0)
    for cell in new_claims:
        boundary = cell_to_boundary(cell)
        poly_coords = [[p[0], p[1]] for p in boundary]
        c_lat, c_lng = cell_to_latlng(cell)

        target_info = scored_targets.get(cell)
        score_val = target_info.final_score if target_info else 2.0
        status_val = target_info.status.upper() if target_info else "UNCLAIMED"
        is_enemy = (target_info.status == HexStatus.ENEMY) if target_info else False

        fill_color = "#e76f51" if is_enemy else "#2a9d8f"
        stroke_color = "#d90429" if is_enemy else "#1d7873"
        badge_text = "ENEMY FLIP" if is_enemy else "NEW UNCLAIMED CAPTURE"

        popup_html = (
            f"<div style='font-family: -apple-system, sans-serif; font-size: 13px; line-height: 1.4;'>"
            f"<span style='background: {fill_color}; color: white; padding: 2px 6px; border-radius: 4px; font-weight: bold; font-size: 11px;'>✨ {badge_text}</span><br><br>"
            f"<b>H3 Hex:</b> <code>{cell}</code><br>"
            f"<b>Status:</b> {status_val}<br>"
            f"<b>Points Gained:</b> <span style='color: #2a9d8f; font-weight: bold; font-size: 16px;'>+{score_val} pts</span><br>"
            f"<small style='color: #888;'>Center: {c_lat:.5f}, {c_lng:.5f}</small>"
            f"</div>"
        )

        folium.Polygon(
            locations=poly_coords,
            color=stroke_color,
            weight=3.5,
            fill=True,
            fill_color=fill_color,
            fill_opacity=0.55,
            popup=folium.Popup(popup_html, max_width=300),
            tooltip=f"✨ NEW CLAIM: {cell} (+{score_val} pts)",
        ).add_to(new_group)

    # 2. Render OUR TEAM'S EXISTING territory in team colour (Agile & Fragile: #8aa4c2)
    for cell in our_territory:
        boundary = cell_to_boundary(cell)
        poly_coords = [[p[0], p[1]] for p in boundary]
        c_lat, c_lng = cell_to_latlng(cell)

        popup_html = (
            f"<div style='font-family: -apple-system, sans-serif; font-size: 13px; line-height: 1.4;'>"
            f"<span style='background: {team_colour}; color: white; padding: 2px 6px; border-radius: 4px; font-weight: bold; font-size: 11px;'>🔵 ALREADY HELD BY OUR TEAM</span><br><br>"
            f"<b>H3 Hex:</b> <code>{cell}</code><br>"
            f"<b>Team:</b> {team_name}<br>"
            f"<b>Score:</b> <span style='color: #555; font-weight: bold;'>0.0 pts (Already Ours)</span><br>"
            f"<small style='color: #888;'>Center: {c_lat:.5f}, {c_lng:.5f}</small>"
            f"</div>"
        )

        folium.Polygon(
            locations=poly_coords,
            color="#4a6d8c",
            weight=2.0,
            fill=True,
            fill_color=team_colour,
            fill_opacity=0.40,
            popup=folium.Popup(popup_html, max_width=280),
            tooltip=f"Our Territory ({team_name}): {cell}",
        ).add_to(ours_group)

    # 3. Render surrounding unvisited / enemy targets that were NOT claimed
    for cell, target in scored_targets.items():
        if cell not in new_claims and cell not in our_territory:
            boundary = cell_to_boundary(cell)
            poly_coords = [[p[0], p[1]] for p in boundary]
            color = "#d90429" if target.status == HexStatus.ENEMY else "#f4a261"

            folium.Polygon(
                locations=poly_coords,
                color=color,
                weight=1.2,
                fill=True,
                fill_color=color,
                fill_opacity=0.15,
                tooltip=f"{target.status.upper()}: {cell} ({target.final_score} pts)",
            ).add_to(other_targets_group)

    new_group.add_to(m)
    ours_group.add_to(m)
    other_targets_group.add_to(m)

    # 4. Render Route Line
    if len(coords) >= 2:
        folium.PolyLine(
            locations=coords,
            color="#4361ee",
            weight=5.5,
            opacity=0.90,
            tooltip=f"Route: {total_distance_m/1000.0:.2f} km | Score: {total_score:.1f} pts",
        ).add_to(m)

        # Start Marker
        folium.Marker(
            location=coords[0],
            popup=f"<b>Start Location</b><br>{coords[0][0]:.5f}, {coords[0][1]:.5f}",
            tooltip="Start",
            icon=folium.Icon(color="green", icon="play", prefix="fa"),
        ).add_to(m)

        # End Marker
        folium.Marker(
            location=coords[-1],
            popup=f"<b>Finish Location</b><br>{coords[-1][0]:.5f}, {coords[-1][1]:.5f}",
            tooltip="Finish",
            icon=folium.Icon(color="red", icon="flag-checkered", prefix="fa"),
        ).add_to(m)

    # Floating Summary Card
    km_str = f"{total_distance_m / 1000.0:.2f} km"
    card_html = f"""
    <div style="
        position: fixed;
        bottom: 25px;
        left: 25px;
        z-index: 1000;
        background: white;
        padding: 14px 18px;
        border-radius: 8px;
        box-shadow: 0 2px 12px rgba(0,0,0,0.22);
        font-family: -apple-system, system-ui, sans-serif;
        font-size: 13.5px;
        line-height: 1.5;
        border-left: 5px solid #4361ee;
        max-width: 320px;
    ">
        <b style="font-size: 15px; color: #1f2328;">Hexroute Optimiser</b><br>
        <b>Team:</b> <span style="color: #4a6d8c; font-weight: bold;">{team_name}</span><br>
        <b>Distance:</b> {km_str}<br>
        <b>New Hexes Claimed:</b> <span style="color: #2a9d8f; font-weight: bold;">+{len(new_claims)}</span><br>
        <b>Existing Territory Passed:</b> {len(our_territory)}<br>
        <b>Total Score Gained:</b> <span style="color: #2a9d8f; font-weight: bold; font-size: 16px;">+{total_score:.1f} pts</span>
        <div style="margin-top: 8px; padding-top: 6px; border-top: 1px solid #e2e8f0; font-size: 10.5px; color: #64748b; line-height: 1.3;">
            ⚠️ <b>Disclaimer:</b> Automated route suggestion. User assumes all risk. Verify public rights-of-way, private land, and safety before following.
        </div>
    </div>
    """
    m.get_root().html.add_child(folium.Element(card_html))

    folium.LayerControl(collapsed=False).add_to(m)
    m.save(str(out_file))
    return out_file
